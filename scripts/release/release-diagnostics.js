'use strict';

const SAFE_RELEASE_ERROR_CODES = Object.freeze([
  'PROCESS_COMMAND_MISMATCH',
  'PROCESS_CWD_MISMATCH',
  'PROCESS_EXPECTED_PID_STILL_RUNNING',
  'PROCESS_INSPECTION_COMMAND_UNAVAILABLE',
  'PROCESS_LOOPBACK_PORT_MISMATCH',
  'PROCESS_RESOURCE_STATE_UNVERIFIED',
  'PROCESS_RESOURCE_STILL_IN_USE',
  'PROCESS_STOP_TIMEOUT',
  'ROLLBACK_ARCHIVE_FAILED',
  'ROLLBACK_CHECKOUT_RESOLUTION_FAILED',
  'ROLLBACK_DATA_SMOKE_FAILED',
  'ROLLBACK_DEPENDENCY_INSTALL_FAILED',
  'ROLLBACK_EXTRACTION_FAILED',
  'ROLLBACK_OBJECT_HASH_FAILED',
  'ROLLBACK_OBJECT_LOOKUP_FAILED',
  'ROLLBACK_OBJECT_MISMATCH',
  'ROLLBACK_OUTPUT_LIMIT_EXCEEDED',
  'ROLLBACK_PORT_RESERVATION_FAILED',
  'ROLLBACK_PROCESS_VALIDATION_FAILED',
  'ROLLBACK_REVISION_UNAVAILABLE',
  'ROLLBACK_ROOT_SMOKE_FAILED',
  'ROLLBACK_START_EXITED',
  'ROLLBACK_START_FAILED',
  'ROLLBACK_START_TIMEOUT',
  'ROLLBACK_STOP_FAILED',
  'ROLLBACK_STOP_VALIDATION_FAILED'
]);

function safeReleaseErrorCategory(error) {
  const code = String(error?.code || '');
  return SAFE_RELEASE_ERROR_CODES.includes(code) ? code : 'REHEARSAL_ERROR';
}

module.exports = { safeReleaseErrorCategory };
